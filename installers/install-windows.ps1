# Agent Mesh — Windows installer (v2.1).
#
# Installs a per-user mesh node: a logon Scheduled Task (no admin
# rights needed) plus a Desktop shortcut to the GUI. Everything lives
# in your user profile.
#
# Idempotent: re-running keeps your existing admin token / vault
# passphrase and data; it rewrites the start script + task + shortcut.
#
# Usage (PowerShell):
#   powershell -ExecutionPolicy Bypass -File .\install-windows.ps1 [-Port 8790] [-NodeName "My Node"]
#
# No sudo/admin anywhere: the task runs as your user at logon.

param(
    [int]$Port = 8790,
    [string]$NodeName = $env:COMPUTERNAME
)

$ErrorActionPreference = "Stop"

$RepoDir  = Split-Path -Parent $PSScriptRoot
$DataDir  = Join-Path $env:USERPROFILE ".agent-mesh-node"
$EnvFile  = Join-Path $DataDir "node.env"
$RunFile  = Join-Path $DataDir "run-node.cmd"
$TaskName = "Agent Mesh Node"

# 1. Python check (python.org install or the py launcher).
$Python = $null
foreach ($cand in @("python", "py")) {
    if (Get-Command $cand -ErrorAction SilentlyContinue) { $Python = $cand; break }
}
if (-not $Python) {
    Write-Error "Python not found. Install Python 3.11+ from https://www.python.org/downloads/ (tick 'Add python.exe to PATH'), then re-run."
    exit 1
}

Write-Host "Agent Mesh Windows installer"
Write-Host "  repo:  $RepoDir"
Write-Host "  data:  $DataDir"
Write-Host "  port:  $Port   node name: $NodeName"

New-Item -ItemType Directory -Force -Path (Join-Path $DataDir "data") | Out-Null

# 2. Secrets env file, created once, never overwritten.
if (-not (Test-Path $EnvFile)) {
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $admin = [Convert]::ToBase64String($bytes).TrimEnd("=").Replace("+","-").Replace("/","_")
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $master = [Convert]::ToBase64String($bytes).TrimEnd("=").Replace("+","-").Replace("/","_")
    @(
        "# Agent Mesh node secrets - keep this file private, never share it."
        "AGENT_MESH_ADMIN=$admin"
        "AGENT_MESH_MASTER=$master"
    ) | Set-Content -Path $EnvFile -Encoding ASCII
    Write-Host "  created $EnvFile with a fresh admin token + vault passphrase"
} else {
    Write-Host "  kept existing $EnvFile (tokens unchanged)"
}

# 3. Start script: cmd reads the env file, then runs the node.
@(
    "@echo off"
    "rem Generated by install-windows.ps1 - starts the Agent Mesh node."
    "for /f ""usebackq tokens=1,* delims=""= eol=#"" %%a in (""$EnvFile"") do set ""%%a=%%b"""
    "set PYTHONPATH=$RepoDir"
    "cd /d ""$RepoDir"""
    "$Python -m agent_mesh.node --port $Port --name ""$NodeName"" --data-dir ""$DataDir\data"""
) | Set-Content -Path $RunFile -Encoding ASCII
Write-Host "  wrote $RunFile"

# 4. Logon scheduled task (user-level, no elevation). Re-registering
#    replaces the old task, which is what makes this idempotent.
$action  = New-ScheduledTaskAction -Execute "cmd.exe" -Argument "/c ""$RunFile"""
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger `
    -Settings $settings -Description "Agent Mesh node (per-user)" -Force | Out-Null
Start-ScheduledTask -TaskName $TaskName
Write-Host "  scheduled task '$TaskName' registered and started"

# 5. Desktop shortcut to the GUI.
$shortcutPath = Join-Path ([Environment]::GetFolderPath("Desktop")) "Agent Mesh.lnk"
$shell = New-Object -ComObject WScript.Shell
$shortcut = $shell.CreateShortcut($shortcutPath)
$shortcut.TargetPath = "http://127.0.0.1:$Port/"
$shortcut.Description = "Agent Mesh control centre"
$shortcut.Save()
Write-Host "  wrote $shortcutPath"

Start-Sleep -Seconds 2
try {
    $resp = Invoke-WebRequest -Uri "http://127.0.0.1:$Port/health" -UseBasicParsing -TimeoutSec 5
    if ($resp.StatusCode -eq 200) { Write-Host "  node is UP: http://127.0.0.1:$Port/" }
} catch {
    Write-Host "  node did not answer yet - check Task Scheduler for '$TaskName'."
}

Write-Host ""
Write-Host "Done. Open the GUI at http://127.0.0.1:$Port/ and log in with the"
Write-Host "AGENT_MESH_ADMIN value from $EnvFile."
Write-Host "Stop it any time with: Stop-ScheduledTask -TaskName '$TaskName'"
