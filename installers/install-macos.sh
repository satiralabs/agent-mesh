#!/usr/bin/env bash
# Agent Mesh — macOS installer (v2.1).
#
# Installs a per-user mesh node as a launchd agent (starts at login,
# kept alive by launchd) plus a Desktop opener for the GUI. No sudo —
# everything lives in your home directory.
#
# Idempotent: re-running keeps your existing admin token / vault
# passphrase and data; it rewrites the agent plist + run script and
# reloads the agent.
#
# Usage:  ./install-macos.sh [--port 8790] [--name "My Node"]
set -euo pipefail

PORT=8790
NODE_NAME="$(hostname -s)"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --port) PORT="$2"; shift 2 ;;
    --name) NODE_NAME="$2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DATA_DIR="$HOME/.agent-mesh-node"
ENV_FILE="$DATA_DIR/node.env"
RUN_SCRIPT="$DATA_DIR/run-node.sh"
LABEL="com.satiralabs.agent-mesh-node"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
DESKTOP_OPENER="$HOME/Desktop/Agent Mesh.command"

command -v python3 >/dev/null || { echo "python3 not found — install Python 3.11+ first (brew install python)." >&2; exit 1; }

echo "Agent Mesh macOS installer"
echo "  repo:  $REPO_DIR"
echo "  data:  $DATA_DIR"
echo "  port:  $PORT   node name: $NODE_NAME"

mkdir -p "$DATA_DIR/data" "$HOME/Library/LaunchAgents"
chmod 700 "$DATA_DIR"

# 1. Secrets env file (0600), created once, never overwritten.
if [[ ! -f "$ENV_FILE" ]]; then
  ADMIN_TOKEN="$(python3 -c 'import secrets; print(secrets.token_urlsafe(32))')"
  MASTER="$(python3 -c 'import secrets; print(secrets.token_urlsafe(32))')"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Agent Mesh node secrets — keep this file 0600, never share it.
AGENT_MESH_ADMIN=$ADMIN_TOKEN
AGENT_MESH_MASTER=$MASTER
EOF
  echo "  created $ENV_FILE with a fresh admin token + vault passphrase (0600)"
else
  echo "  kept existing $ENV_FILE (tokens unchanged)"
fi
chmod 600 "$ENV_FILE"

# 2. Run script: launchd does not read env files, so the script
#    sources it and execs the node.
cat > "$RUN_SCRIPT" <<EOF
#!/bin/sh
# Generated by install-macos.sh — starts the Agent Mesh node.
set -a
. "$ENV_FILE"
set +a
export PYTHONPATH="$REPO_DIR"
cd "$REPO_DIR"
exec /usr/bin/env python3 -m agent_mesh.node --port $PORT --name "$NODE_NAME" --data-dir "$DATA_DIR/data"
EOF
chmod 700 "$RUN_SCRIPT"
echo "  wrote $RUN_SCRIPT"

# 3. launchd agent plist.
cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array><string>$RUN_SCRIPT</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>$DATA_DIR/node.out.log</string>
  <key>StandardErrorPath</key><string>$DATA_DIR/node.err.log</string>
</dict>
</plist>
EOF
echo "  wrote $PLIST"

# 4. Desktop opener for the GUI.
cat > "$DESKTOP_OPENER" <<EOF
#!/bin/sh
open "http://127.0.0.1:$PORT/"
EOF
chmod +x "$DESKTOP_OPENER"
echo "  wrote $DESKTOP_OPENER"

# 5. (Re)load the agent — bootout first so re-runs are clean.
launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
launchctl kickstart -k "gui/$(id -u)/$LABEL" 2>/dev/null || true

sleep 1
if curl -fsS "http://127.0.0.1:$PORT/health" >/dev/null 2>&1; then
  echo "  node is UP: http://127.0.0.1:$PORT/"
else
  echo "  node did not answer yet — check $DATA_DIR/node.err.log"
fi

echo
echo "Done. Open the GUI at http://127.0.0.1:$PORT/ and log in with the"
echo "AGENT_MESH_ADMIN value from $ENV_FILE."
echo "Stop it any time with: launchctl bootout gui/\$(id -u)/$LABEL"
