#!/usr/bin/env python3
"""Generate the Agent Mesh logo set (v2.2.1).

The mark: six satellite nodes on a hexagon around one highlighted hub,
ring + spoke links stroked with the indigo -> cyan gradient the GUI
uses, satellites in light slate. It reads as a network at 512px and as
a hub-and-dots glyph at 20px.

Outputs (paths relative to the repo root):
  logo.svg / logo-lockup.svg          the mark, and mark + wordmark
  logo-{512,192,64,32}.png            transparent renders of the mark
  app-icon.svg                        mark on the dark app tile
  agent_mesh/web2/icons/icon-*.png    PWA / favicon set (from app-icon)
  extension/icons/icon-*.png          browser extension set
  desktop/src-tauri/icons/*           Tauri icon set (svg + pngs + ico)

PNG rendering needs cairosvg (pip install cairosvg). The SVGs are the
source of truth and are written even without it.
"""
import math
import os
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))

C = 120.0          # centre of the 240x240 mark canvas
R = 62.0           # satellite orbit radius
SAT_R = 10         # satellite radius
HUB_R = 17         # hub radius
LINK_W = 8         # link stroke width

ANGLES = (-90, -30, 30, 90, 150, 210)
SATS = [(C + R * math.cos(math.radians(a)),
         C + R * math.sin(math.radians(a))) for a in ANGLES]


def f(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def mark_group():
    ring = " ".join(f"{f(x)},{f(y)}" for x, y in SATS)
    spokes = "".join(
        f'<line x1="{f(C)}" y1="{f(C)}" x2="{f(x)}" y2="{f(y)}"/>'
        for x, y in SATS)
    sats = "".join(f'<circle cx="{f(x)}" cy="{f(y)}" r="{SAT_R}"/>'
                   for x, y in SATS)
    return f"""  <g stroke="url(#am-links)" stroke-width="{LINK_W}"
     stroke-linecap="round" stroke-linejoin="round" fill="none">
    <polygon points="{ring}"/>
    {spokes}
  </g>
  <g fill="#e9eef9">{sats}</g>
  <circle cx="{f(C)}" cy="{f(C)}" r="{HUB_R}" fill="url(#am-hub)"/>
  <circle cx="{f(C)}" cy="{f(C)}" r="6.5" fill="#ffffff"/>"""


DEFS = """  <defs>
    <linearGradient id="am-links" x1="0" y1="0" x2="240" y2="240"
                    gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#6366f1"/>
      <stop offset=".55" stop-color="#818cf8"/>
      <stop offset="1" stop-color="#22d3ee"/>
    </linearGradient>
    <linearGradient id="am-hub" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#818cf8"/>
      <stop offset="1" stop-color="#06b6d4"/>
    </linearGradient>
  </defs>"""

LOGO_SVG = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 240 240">
  <!-- Agent Mesh mark: hexagonal node mesh around a highlighted hub.
       Generated by make-logo.py — edit there, not here. -->
{DEFS}
{mark_group()}
</svg>
"""

LOCKUP_SVG = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 820 240">
  <!-- Agent Mesh lockup: mark + wordmark. Generated by make-logo.py. -->
{DEFS}
{mark_group()}
  <text x="278" y="141" font-family="Inter, 'Segoe UI', Roboto,
        'Helvetica Neue', Arial, sans-serif" font-size="78"
        font-weight="600" letter-spacing="1.5" fill="#edf1fa">Agent Mesh</text>
</svg>
"""

APP_ICON_SVG = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <!-- Agent Mesh app icon: the mark on the dark tile the GUI uses.
       Generated by make-logo.py. -->
  <defs>
    <radialGradient id="am-glow" cx=".22" cy=".12" r="1.1">
      <stop offset="0" stop-color="#6366f1" stop-opacity=".38"/>
      <stop offset=".6" stop-color="#6366f1" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="512" height="512" rx="104" fill="#0b1020"/>
  <rect width="512" height="512" rx="104" fill="url(#am-glow)"/>
{DEFS}
  <g transform="translate(46 46) scale(1.75)">
{mark_group()}
  </g>
</svg>
"""


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w") as fh:
        fh.write(text)
    print("wrote", path)


def main():
    write("logo.svg", LOGO_SVG)
    write("logo-lockup.svg", LOCKUP_SVG)
    write("app-icon.svg", APP_ICON_SVG)
    write(os.path.join("desktop", "src-tauri", "icons", "icon.svg"),
          APP_ICON_SVG)
    try:
        import cairosvg
    except ImportError:
        print("cairosvg not installed — SVGs written, PNGs skipped.\n"
              "Install with: pip install cairosvg", file=sys.stderr)
        return 1

    def render(svg_text, path, size):
        full = os.path.join(ROOT, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        cairosvg.svg2png(bytestring=svg_text.encode(),
                         write_to=full,
                         output_width=size, output_height=size)
        print("rendered", path, size)

    for size in (512, 192, 64, 32):
        render(LOGO_SVG, f"logo-{size}.png", size)
    for size in (128, 256, 512):
        render(APP_ICON_SVG,
               os.path.join("agent_mesh", "web2", "icons",
                            f"icon-{size}.png"), size)
    for size in (32, 128):
        render(APP_ICON_SVG,
               os.path.join("extension", "icons", f"icon-{size}.png"),
               size)
    # Tauri set: 512 master + derived sizes + multi-size .ico (via PIL).
    render(APP_ICON_SVG,
           os.path.join("desktop", "src-tauri", "icons", "icon.png"), 512)
    from PIL import Image
    master = Image.open(os.path.join(
        ROOT, "desktop", "src-tauri", "icons", "icon.png"))
    for name, size in (("32x32.png", 32), ("128x128.png", 128),
                       ("128x128@2x.png", 256)):
        out = os.path.join(ROOT, "desktop", "src-tauri", "icons", name)
        master.resize((size, size), Image.LANCZOS).save(out)
        print("rendered", os.path.relpath(out, ROOT), size)
    ico = os.path.join(ROOT, "desktop", "src-tauri", "icons", "icon.ico")
    master.save(ico, sizes=[(s, s) for s in
                            (16, 24, 32, 48, 64, 128, 256)])
    print("rendered", os.path.relpath(ico, ROOT), "ico")
    return 0


if __name__ == "__main__":
    sys.exit(main())
